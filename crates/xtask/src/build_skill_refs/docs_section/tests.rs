use super::*;

fn fake<'a>(files: &'a [(&'a str, &'a str)]) -> impl Fn(&str) -> Result<String> + 'a {
    move |p: &str| {
        files
            .iter()
            .find(|(k, _)| *k == p)
            .map(|(_, v)| v.to_string())
            .ok_or_else(|| anyhow::anyhow!("no such file {p}"))
    }
}

